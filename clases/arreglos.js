//push=>agregar al final
let lista=[]
lista.push("a")
console.log(lista)
lista.push("b")
console.log(lista)
//unshift=>agregar al inicio de un arreglo
lista.unshift("c")
console.log(lista)
//pop=>eliminar elemto al final
lista.pop()
console.log(lista)
//shift=>elimina al inicio de la lista
lista.shift()
console.log(lista)
